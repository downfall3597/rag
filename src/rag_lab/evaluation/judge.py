"""LLM-as-judge: score a generated answer against a reference answer and its
cited sources, on three independent criteria.

Unlike build_prompt/extract_citations in generation/anthropic_gen.py (which
make the model CITE its sources), this closes a gap CONCEPTS.md already
calls out: a citation marker only proves the model claimed to use a source,
never that the claim next to it is actually TRUE of that source. Judging
that requires a second model call, reading the claim and the source side by
side.

Why a stronger model as judge than the one generating answers: a model
grading its own homework is a known bias risk. The judge here defaults to
a different (stronger) model than AnthropicGenerator's default, on purpose.

build_judge_prompt and parse_judge_response are the two functions worth
implementing by hand -- designing the rubric and getting reliable
structured output back out of free text are real, separate skills from
anything built so far in this project (neither is a formula to derive).
AnswerJudge's API-calling plumbing is scaffolded, same pattern as
AnthropicGenerator.
"""

import json
from typing import Callable

import anthropic
from pydantic import BaseModel, Field

from rag_lab.models import RetrievedChunk

DEFAULT_JUDGE_MODEL = "claude-sonnet-5"
DEFAULT_BEDROCK_JUDGE_MODEL = "us.anthropic.claude-sonnet-5"


class JudgeResult(BaseModel):
    faithfulness: float = Field(ge=0.0, le=1.0)
    answer_relevance: float = Field(ge=0.0, le=1.0)
    correctness: float = Field(ge=0.0, le=1.0)
    reasoning: str


def build_judge_prompt(
    question: str,
    answer: str,
    reference_answer: str,
    cited_chunks: list[RetrievedChunk],
) -> str:
    """Build the prompt sent to the judge model.

    YOUR TURN: implement this.

    Present all four pieces of information to the judge:
    - `question`: what was asked.
    - `answer`: what the system under test actually generated.
    - `reference_answer`: the known-correct answer to compare against.
    - `cited_chunks`: the source text(s) the answer claims to be grounded
      in (use each chunk's `.chunk.text`) -- the judge needs these to check
      faithfulness, not just take the citation marker's existence on faith.

    Instruct the judge to score three criteria, each a float from 0.0 to
    1.0:
    - faithfulness: is every claim in `answer` actually supported by
      `cited_chunks`? (1.0 = fully grounded, 0.0 = fabricated/unsupported)
    - answer_relevance: does `answer` actually address `question`,
      independent of whether it's correct or grounded?
    - correctness: does `answer` match what `reference_answer` says,
      factually (not word-for-word)?

    Instruct the judge to respond with ONLY a single JSON object, no other
    text, with exactly these keys: "faithfulness", "answer_relevance",
    "correctness" (each a float 0.0-1.0), and "reasoning" (a short string
    explaining the scores). Being explicit about "ONLY a JSON object, no
    markdown code fences, no commentary before or after" matters here --
    parse_judge_response has to reliably extract this back out.
    """
    return f"""
        You are a judge model. You will be given a question, an answer generated by a system and the cited chunks that the answer claims to be grounded in, you will also be provided with a reference answer.
        Your task is to evaluate the answer based on the following criteria:
        1. faithfulness: is every claim in `answer` actually supported by `cited_chunks`? (1.0 = fully grounded, 0.0 = fabricated/unsupported)
        2. answer_relevance: does `answer` actually address `question`, independent of whether it's correct or grounded?
        3. correctness: does `answer` match what `reference_answer` says, factually (not word-for-word)?

        RULES:
        - Respond with ONLY a single JSON object, no other text, with exactly these keys:
            - "faithfulness": float 0.0-1.0
            - "answer_relevance": float 0.0-1.0
            - "correctness": float 0.0-1.0
            - "reasoning": a short string explaining the scores.
        - Do not include any markdown code fences, or any commentary before or after the JSON object

        QUESTION: {question}
        ANSWER: {answer}
        REFERENCE ANSWER: {reference_answer}
        CITED CHUNKS: {"; ".join(chunk.chunk.text for chunk in cited_chunks)}
    """

def parse_judge_response(response_text: str) -> JudgeResult:
    """Parse the judge model's raw text response into a JudgeResult.

    YOUR TURN: implement this.

    The judge was instructed to respond with only a JSON object, but models
    don't always follow formatting instructions exactly -- it may still
    wrap the JSON in a markdown code fence (```json ... ```) or add a
    stray sentence before/after. Handle at least the code-fence case:
    strip ```json / ``` markers if present before parsing.

    Steps:
    1. Strip any surrounding markdown code fence from `response_text`.
    2. Parse the remaining text as JSON (`json.loads`).
    3. Construct and return `JudgeResult(**parsed)` -- the Field(ge=0.0,
       le=1.0) constraints on JudgeResult will raise a validation error on
       their own if the judge returned an out-of-range score, so you don't
       need to re-check the ranges yourself here.
    """
    # Strip code fences if present
    if response_text.startswith("```json"):
        response_text = response_text[len("```json"):].strip()
    elif response_text.startswith("```"):
        response_text = response_text[len("```"):].strip()
    if response_text.endswith("```"):
        response_text = response_text[:-len("```")].strip()

    # Parse JSON
    parsed = json.loads(response_text)

    # Construct and return JudgeResult
    return JudgeResult(**parsed)

def _anthropic_call_model(model: str, client: anthropic.Anthropic | None = None) -> Callable[[str], str]:
    client = client or anthropic.Anthropic()

    def call(prompt: str) -> str:
        response = client.messages.create(
            model=model,
            max_tokens=1024,
            messages=[{"role": "user", "content": prompt}],
        )
        return response.content[0].text

    return call


def _bedrock_call_model(model_id: str, region: str) -> Callable[[str], str]:
    import boto3

    client = boto3.Session(region_name=region).client("bedrock-runtime")

    def call(prompt: str) -> str:
        response = client.converse(
            modelId=model_id,
            messages=[{"role": "user", "content": [{"text": prompt}]}],
            inferenceConfig={"maxTokens": 1024},
        )
        return response["output"]["message"]["content"][0]["text"]

    return call


class AnswerJudge:
    """Judges an answer by sending build_judge_prompt's output through
    `call_model` (any str -> str callable) and parsing the result.
    Decoupling "how to call an LLM" from "what to ask it" is what lets the
    same judge logic run against either the direct Anthropic API or AWS
    Bedrock -- construct via from_anthropic()/from_bedrock(), or pass your
    own call_model directly (e.g. a test double).
    """

    def __init__(self, call_model: Callable[[str], str]):
        self._call_model = call_model

    @classmethod
    def from_anthropic(cls, model: str = DEFAULT_JUDGE_MODEL, client: anthropic.Anthropic | None = None) -> "AnswerJudge":
        return cls(_anthropic_call_model(model, client))

    @classmethod
    def from_bedrock(cls, model_id: str = DEFAULT_BEDROCK_JUDGE_MODEL, region: str = "us-east-2") -> "AnswerJudge":
        return cls(_bedrock_call_model(model_id, region))

    def judge(
        self,
        question: str,
        answer: str,
        reference_answer: str,
        cited_chunks: list[RetrievedChunk],
    ) -> JudgeResult:
        prompt = build_judge_prompt(question, answer, reference_answer, cited_chunks)
        return parse_judge_response(self._call_model(prompt))
